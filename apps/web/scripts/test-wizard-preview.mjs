import { chromium } from 'playwright';
import fs from 'fs';
const BASE_URL = 'http://localhost:5173';
const browser = await chromium.launch({ headless: true });
const context = await browser.newContext({ viewport: { width: 1400, height: 900 } });
const page = await context.newPage();
await page.goto(`${BASE_URL}/wizard`);
await page.waitForSelector('text=AI 课件生成向导');
const testFilePath = './test-source-wizard.md';
fs.writeFileSync(testFilePath, '# 人工智能简介\n## 什么是AI\nAI 是由人制造的系统表现出的智能。\n## 应用\nAI 在医疗、教育、交通等领域有广泛应用。\n## 机器学习\n机器学习通过数据训练模型。\n## 深度学习\n深度学习使用神经网络。\n## 小结\n本节课介绍 AI 基本概念和应用。');
const fileInput = page.locator('input[type="file"]');
await fileInput.setInputFiles(testFilePath);
await page.click('text=下一步');
await page.waitForTimeout(1000);
await page.fill('textarea', '生成 5 页人工智能入门课件');
await page.click('text=生成大纲');
await page.waitForSelector('text=确认课件大纲', { timeout: 300000 });
await page.click('text=确认并生成课件');
await page.locator('text=课件生成完成！').waitFor({ timeout: 600000 });
console.log('Generation complete');
await page.screenshot({ path: '/tmp/wizard-complete.png' });
const buttons = await page.locator('button').allInnerTexts();
console.log('Buttons after complete:', buttons);
await page.locator('button:has-text("预览播放")').click();
await page.waitForURL('**/player', { timeout: 30000 });
console.log('Navigated to player, url:', page.url());
await page.waitForTimeout(3000);
await page.screenshot({ path: '/tmp/player-preview.png' });
fs.unlinkSync(testFilePath);
await browser.close();
